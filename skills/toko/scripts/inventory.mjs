#!/usr/bin/env node
// Lists every hard-coded color, shadow and font size in a project, so they can be moved onto
// Toko tokens. Read-only. Prints JSON to stdout. Node 18+, no dependencies.

import { readdirSync, readFileSync, statSync } from "node:fs"
import { extname, join, relative, resolve } from "node:path"
import { pathToFileURL } from "node:url"

const HELP = `Usage: node inventory.mjs [dir] [--limit N]

Scans [dir] (default: the current folder) for values that should come from Toko tokens:
  color       hex, rgb(), hsl(), oklch(), lab() and color() values
  shadow      box-shadow values that aren't var(--…)
  font-size   font sizes that aren't var(--…)
  tw-color    Tailwind palette classes (bg-blue-500, bg-white), which the tokens replace
  tw-size     Tailwind font sizes (text-sm, text-2xl), replaced by Toko's type roles
  tw-shadow   Tailwind shadows Toko doesn't define (shadow, shadow-inner, and shadow-2xs or shadow-2xl
              unless the exported palette has 7 or 9 levels)
  tw-custom   Tailwind arbitrary values (bg-[#fff], text-[13px], shadow-[…])
  tw-dark     dark: overrides to a hard-coded color, which the tokens make unnecessary

Skips node_modules, build output, agent skill folders, files generated by Toko, comments,
and lines marked toko-keep (values kept on purpose, like logos or chart data).
Prints {root, files, total, byKind, findings[], truncated}. --limit caps findings (default 300).`

export const SOURCE_EXTENSIONS = new Set([
    ".css", ".scss", ".sass", ".less", ".pcss", ".styl",
    ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".mts", ".cts",
    ".vue", ".svelte", ".astro", ".html", ".htm",
])

export const SKIP_DIRS = new Set([
    "node_modules", ".git", ".hg", "dist", "build", "out", ".next", ".nuxt", ".output", ".svelte-kit",
    ".astro", ".vercel", ".netlify", ".turbo", ".cache", "coverage", "storybook-static", "vendor",
    // Where agents keep skills, this one included: its own examples aren't the project's code.
    ".claude", ".agents", ".cursor", ".codex", ".gemini", ".github", ".copilot", ".windsurf", ".kiro", ".opencode",
])

/** A line marked like this is kept on purpose (a logo, chart data) and skipped by both scripts. */
export const KEEP = /toko-keep/

export const TOKO_MARK = "Generated by Toko"

const TW_PALETTE =
    "slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose"
const TW_COLOR_UTILS = "bg|text|border(?:-[trblxyse])?|ring|ring-offset|outline|fill|stroke|from|via|to|divide|placeholder|decoration|accent|caret|shadow"

const RULES = [
    // Not a CSS id selector (`#abc {`) or a link to an anchor.
    { kind: "color", re: /(?<![\w&/[-])#(?:[\da-fA-F]{8}|[\da-fA-F]{6}|[\da-fA-F]{3,4})\b(?![-\w])(?!\s*[{,]\s*$)(?!\s*\{)/g },
    { kind: "color", re: /(?<![\w.[-])(?:rgba?|hsla?|oklch|oklab|lab|lch|hwb|color)\([^()]*\)/g },
    { kind: "shadow", re: /box-shadow\s*:\s*(?!\s*(?:var\(|none|inherit|initial|unset|revert))[^;"'}]+/gi },
    { kind: "shadow", re: /boxShadow\s*:\s*["'`](?!\s*(?:var\(|none))[^"'`]+["'`]/g },
    { kind: "font-size", re: /font-size\s*:\s*(?!\s*(?:var\(|inherit|initial|unset|revert|100%|1em\b))[\d.]+(?:px|rem|em|pt)\b/gi },
    { kind: "font-size", re: /fontSize\s*:\s*(?:["'`][\d.]+(?:px|rem|em|pt)["'`]|\d+(?=\s*[,}]))/g },
    { kind: "tw-dark", re: new RegExp(`(?<![\\w-])dark:(?:${TW_COLOR_UTILS})-(?:(?:${TW_PALETTE})-\\d{2,3}|white|black|\\[[^\\]\\s]*\\])(?:/\\d+)?(?![\\w-])`, "g") },
    { kind: "tw-color", re: new RegExp(`(?<![\\w:-])(?:[\\w-]+:)*(?:${TW_COLOR_UTILS})-(?:(?:${TW_PALETTE})-\\d{2,3}|white|black)(?:/\\d+)?(?![\\w-])`, "g") },
    { kind: "tw-size", re: /(?<![\w-])(?:[\w-]+:)*text-(?:xs|sm|base|lg|[2-9]?xl)(?![\w-])/g },
    { kind: "tw-shadow", re: /(?<![\w-])(?:[\w-]+:)*shadow-(?:[23]xs|[23]xl|inner)(?![\w-])/g },
    // The bare `shadow` class: first in a class attribute, or among other classes in a string (cn("rounded shadow")).
    { kind: "tw-shadow", re: /(?<=\bclass(?:Name)?\s*=\s*["'`]|["'`][^"'`]*\s)(?:[\w-]+:)*shadow(?=[\s"'`])/g },
    { kind: "tw-custom", re: /(?<![\w-])(?:[\w-]+:)*(?:bg|text|border|ring|outline|fill|stroke|shadow|from|via|to|divide)-\[(?:#|rgb|hsl|oklch|color|\d)[^\]\s]*\]/g },
]

/** Every source file under `root`, skipping dependencies, build output and Toko's own files. */
export function sourceFiles(root) {
    const out = []
    const walk = dir => {
        let entries
        try {
            entries = readdirSync(dir, { withFileTypes: true })
        } catch {
            return
        }
        for (const entry of entries) {
            const path = join(dir, entry.name)
            if (entry.isDirectory()) {
                if (!SKIP_DIRS.has(entry.name)) walk(path)
            } else if (entry.isFile() && SOURCE_EXTENSIONS.has(extname(entry.name)) && !/\.min\.\w+$/.test(entry.name)) {
                out.push(path)
            }
        }
    }
    walk(root)
    return out
}

export const isTokoFile = text => text.slice(0, 200).includes(TOKO_MARK)

/** Hard-coded values in one file's text. Comments and lines marked toko-keep are skipped. */
export function scanText(text) {
    const findings = []
    const lines = text.split("\n")
    // The closing of the comment we're inside: CSS/JS or HTML.
    let closing = null
    lines.forEach((line, i) => {
        let code = line
        if (closing) {
            const end = code.indexOf(closing)
            if (end === -1) return
            code = code.slice(end + closing.length)
            closing = null
        }
        code = code.replace(/\/\*.*?\*\//g, "").replace(/<!--.*?-->/g, "")
        for (const [start, end] of [["/*", "*/"], ["<!--", "-->"]]) {
            const open = code.indexOf(start)
            if (open !== -1) {
                code = code.slice(0, open)
                closing = end
            }
        }
        // Checked after the comments, so a kept line still closes a comment it ends.
        if (KEEP.test(line)) return
        code = code.replace(/(^|[^:"'])\/\/.*$/, "$1")
        for (const { kind, re } of RULES) {
            for (const m of code.matchAll(re)) {
                const value = m[0].trim()
                // A dark: override is reported once, as tw-dark, not again as a palette class.
                if (kind !== "tw-dark" && kind.startsWith("tw-") && /(^|:)dark:/.test(value)) continue
                findings.push({ line: i + 1, kind, value: value.length > 120 ? `${value.slice(0, 117)}...` : value })
            }
        }
    })
    return findings
}

/** The shadow levels Toko's files define (`--shadow-2xl:`), which a palette with 7 or 9 levels adds. */
export const tokoShadows = text => new Set([...text.matchAll(/--shadow-([\w-]+)\s*:/g)].map(m => m[1]))

export function inventory(root, limit = 300) {
    const texts = []
    const shadows = new Set()
    for (const file of sourceFiles(root)) {
        try {
            if (statSync(file).size > 1_000_000) continue
            const text = readFileSync(file, "utf8")
            if (isTokoFile(text)) for (const id of tokoShadows(text)) shadows.add(id)
            else texts.push([file, text])
        } catch {
            continue
        }
    }
    const findings = []
    const byKind = {}
    let scanned = 0
    for (const [file, text] of texts) {
        scanned++
        for (const f of scanText(text)) {
            // shadow-2xl is Toko's own when the exported palette has it.
            if (f.kind === "tw-shadow" && shadows.has(f.value.replace(/^(?:[\w-]+:)*shadow-/, ""))) continue
            byKind[f.kind] = (byKind[f.kind] ?? 0) + 1
            findings.push({ file: relative(root, file), ...f })
        }
    }
    return {
        root,
        files: scanned,
        total: findings.length,
        byKind,
        findings: findings.slice(0, limit),
        truncated: findings.length > limit,
    }
}

function main(argv) {
    if (argv.includes("--help") || argv.includes("-h")) {
        console.log(HELP)
        return 0
    }
    const limitAt = argv.indexOf("--limit")
    const limit = limitAt === -1 ? 300 : Number(argv[limitAt + 1])
    if (!Number.isInteger(limit) || limit < 0) {
        console.error("--limit needs a whole number, e.g. --limit 100")
        return 2
    }
    const dir = argv.find((a, i) => !a.startsWith("-") && (limitAt === -1 || i !== limitAt + 1)) ?? "."
    const root = resolve(dir)
    try {
        if (!statSync(root).isDirectory()) throw new Error()
    } catch {
        console.error(`Not a folder: ${dir}. Pass the project folder, e.g. node inventory.mjs .`)
        return 2
    }
    console.log(JSON.stringify(inventory(root, limit), null, 2))
    return 0
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
    process.exitCode = main(process.argv.slice(2))
}
